// The rule reference is the documentation that the catalog and the rules'
// examples generate: a Markdown page for each rule and their index under
// docs/rules, the JSON Schema of the configuration under docs/schema, and
// the block of the README that lists the rules. The test of this package
// compares them with the repository, and regenerates them with -update.

const (
	// RegenerateCommand is the command that regenerates the rule
	// reference.
	RegenerateCommand = "go test ./internal/ruledocs -update"

	// generatedNotice starts each generated Markdown file.
	generatedNotice = "<!-- Generated by: " + RegenerateCommand + ". Do not edit. -->"

	// schemaNotice is the top-level $comment of the generated schema.
	schemaNotice = "Generated by: " + RegenerateCommand + ". Do not edit."

	// ReadmeBlockBegin and ReadmeBlockEnd mark the block of the README
	// that UpdateReadme writes, each on a line of its own.
	ReadmeBlockBegin = "<!-- BEGIN GENERATED RULES -->"
	ReadmeBlockEnd   = "<!-- END GENERATED RULES -->"

	// rulesDir and schemaDir are the directories of the rule reference,
	// relative to the repository's root.
	rulesDir  = "docs/rules"
	schemaDir = "docs/schema"

	// indexName is the name of the index of the rule pages.
	indexName = "README.md"

	// schemaName is the name of the configuration's JSON Schema.
	schemaName = "gomdlint.schema.json"
)

// RulePagesURL is where the rule pages of docs/rules are published: on main
// of gomdlint's repository, where the JSON Schema's $id (SchemaURL) points
// too. A page there describes the rule as the latest gomdlint has it, and
// its address holds only while the rule keeps its name.
const RulePagesURL = "https://github.com/yaklabco/gomdlint/blob/main/" + rulesDir + "/"

// PageURL returns the published address of the page of entry's rule (see
// RulePagesURL), or "" when the rule has no generated page: when it is not
// a built-in rule, such as a custom rule, even one that takes a built-in
// rule's ID and name.
func PageURL(entry Entry) string {
	if !entry.builtIn() {
		return ""
	}
	return RulePagesURL + url.PathEscape(entry.Name) + ".md"
}

// RuleHelp documents rule, whose catalog entry is meta, or the zero entry
// when it has none, for a SARIF rule descriptor: as the page that explain
// prints, in text, and that explain --format markdown prints, in its
// built-in state, with the address of its generated page (see PageURL),
// "" for a rule without one. It reports false when a page cannot be
// written, as when the rule's embedded example does not parse, which the
// tests of this package rule out for the built-in rules. Its signature is
// that of reporter.Options.RuleHelp.
func RuleHelp(rule lint.Rule, meta lint.RuleMeta) (string, string, string, bool) {
	entry := NewEntry(rule, meta)
	var text, markdown strings.Builder
	if WriteTextPage(&text, entry, "") != nil || WriteMarkdownPage(&markdown, entry) != nil {
		return "", "", "", false
	}
	return text.String(), markdown.String(), PageURL(entry), true
}

// ReferenceDirs returns the directories that hold the files of the rule
// reference, relative to the repository's root, which hold nothing else.
func ReferenceDirs() []string {
	return []string{rulesDir, schemaDir}
}

// IsGenerated reports whether content, a file of the rule reference, says
// that it is generated, as each file that ReferenceFiles returns does: a
// Markdown file whose first line is the generated notice, or a JSON object
// whose top-level $comment is the schema's notice. A hand-written file
// that quotes a notice elsewhere, such as in an example, is not generated.
func IsGenerated(content []byte) bool {
	if bytes.HasPrefix(content, []byte(generatedNotice+"\n")) {
		return true
	}
	// A map, unlike a struct field, matches the key exactly, not in any case.
	var object map[string]json.RawMessage
	if err := json.Unmarshal(content, &object); err != nil {
		return false
	}
	var comment string
	raw, found := object["$comment"]
	return found && json.Unmarshal(raw, &comment) == nil && comment == schemaNotice
}

// ReferenceFiles returns the files of the rule reference for entries, keyed
// by their paths relative to the repository's root, with slashes: the page
// of each rule, docs/rules/<name>.md, their index, docs/rules/README.md,
// and the configuration's JSON Schema, docs/schema/gomdlint.schema.json.
// Pages and the index link to each other with relative links, which work
// on GitHub, in forks and in a checkout, at every commit.
func ReferenceFiles(entries []Entry) (map[string][]byte, error) {
	files := make(map[string][]byte, len(entries)+2) // The pages, the index and the schema.
	for _, entry := range entries {
		var page bytes.Buffer
		page.WriteString(generatedNotice + "\n\n")
		if err := WriteMarkdownPage(&page, entry); err != nil {
			return nil, err
		}
		files[rulesDir+"/"+entry.Name+".md"] = page.Bytes()
	}

	var index markdownDocument
	index.add(generatedNotice)
	index.heading(1, "Rules")
	index.add(markdownProse(countsText(entries) + " Each rule's page says what the rule checks and why, " +
		"lists its options, says what its fix does, and shows how to configure the rule and silence it."))
	addRuleTables(&index, entries, 2, func(entry Entry) string { return entry.Name + ".md" })
	files[rulesDir+"/"+indexName] = []byte(index.String())

	var schema bytes.Buffer
	if err := WriteSchema(&schema, entries); err != nil {
		return nil, err
	}
	files[schemaDir+"/"+schemaName] = schema.Bytes()

	return files, nil
}

// UpdateReadme returns readme, a README, with the lines between its
// ReadmeBlockBegin and ReadmeBlockEnd lines replaced by the rules of
// entries: their counts, and a table for each category of the rules' names,
// linked to their pages, IDs, fix support and descriptions. The block's
// headings are of level 3, under the README's section on rules. Each
// marker must stand on a line of its own, once, the begin marker first.
// The block's lines end as the begin marker's line does, in LF or CRLF.
func UpdateReadme(readme []byte, entries []Entry) ([]byte, error) {
	text := string(readme)
	begin, beginErr := markerLine(text, ReadmeBlockBegin)
	end, endErr := markerLine(text, ReadmeBlockEnd)
	if err := errors.Join(beginErr, endErr); err != nil {
		return nil, err
	}
	if end.start < begin.start {
		return nil, fmt.Errorf("the README's %s comes before its %s", ReadmeBlockEnd, ReadmeBlockBegin)
	}

	var block markdownDocument
	block.add(generatedNotice, markdownProse(countsText(entries)))
	addRuleTables(&block, entries, 3, func(entry Entry) string { return rulesDir + "/" + entry.Name + ".md" })

	newline := cmp.Or(begin.ending, "\n")
	lines := strings.ReplaceAll("\n"+block.String()+"\n", "\n", newline)
	return []byte(text[:begin.next] + lines + text[end.start:]), nil
}

// readmeLine is where a line of a README starts, where the next line
// starts, and how the line ends: "\n", "\r\n", or "" for a last line
// without a line ending.
type readmeLine struct {
	start, next int
	ending      string
}

// markerLine returns the line of text, a README, that holds marker and
// nothing else, apart from its line ending, as an HTML block of its own at
// the top level of the README, which GitHub Flavored Markdown reads it as.
// So a marker inside a code block, a longer HTML comment, a list item or a
// blockquote, where a README may show the markers, marks nothing. It fails
// when no line, or more than one, holds marker.
func markerLine(text, marker string) (readmeLine, error) {
	markdown := goldmark.New(goldmark.WithExtensions(extension.GFM)) // As GitHub reads a README.
	doc := markdown.Parser().Parse(gmtext.NewReader([]byte(text)))

	var found []readmeLine
	for node := doc.FirstChild(); node != nil; node = node.NextSibling() {
		html, isHTML := node.(*ast.HTMLBlock)
		if !isHTML || html.Lines().Len() != 1 || html.HasClosure() {
			continue
		}
		start := html.Lines().At(0).Start
		if start > 0 && text[start-1] != '\n' {
			continue // The block starts after indentation.
		}
		next := len(text)
		if idx := strings.IndexByte(text[start:], '\n'); idx >= 0 {
			next = start + idx + 1
		}
		content := text[start:next]
		withoutEnding := strings.TrimSuffix(strings.TrimSuffix(content, "\n"), "\r")
		if withoutEnding == marker {
			found = append(found, readmeLine{start: start, next: next, ending: content[len(withoutEnding):]})
		}
	}

	switch len(found) {
	case 0:
		return readmeLine{}, fmt.Errorf("the README has no line %s", marker)
	case 1:
		return found[0], nil
	default:
		return readmeLine{}, fmt.Errorf("the README has %d lines %s, and needs one", len(found), marker)
	}
}

// countsText says how many rules entries holds, and how many fix what
// they find.
func countsText(entries []Entry) string {
	fixable := 0
	for _, entry := range entries {
		if entry.Fixable {
			fixable++
		}
	}
	return fmt.Sprintf("gomdlint has %d %s, and %d of them can fix what they find.",
		len(entries), plural(len(entries), "rule", "rules"), fixable)
}

// addRuleTables adds to doc, for each category of entries, a heading of
// level with the category's title and a table of its rules: their names,
// linked to link(entry), IDs, fix support and descriptions.
func addRuleTables(doc *markdownDocument, entries []Entry, level int, link func(Entry) string) {
	for _, group := range groups(entries, config.RuleFormatName) {
		doc.heading(level, group.title())
		rows := make([]string, 0, len(group.entries)+2) // The header and delimiter rows, then a row per rule.
		rows = append(rows, "| Name | ID | Fix | Description |", "| --- | --- | --- | --- |")
		for _, entry := range group.entries {
			name := markdownCode(entry.Name)
			if link != nil {
				name = "[" + name + "](" + link(entry) + ")"
			}
			rows = append(rows, "| "+strings.Join([]string{
				name, markdownText(entry.ID), yesNo(entry.Fixable), markdownText(entry.Description),
			}, " | ")+" |")
		}
		doc.add(strings.Join(rows, "\n"))
	}
}
